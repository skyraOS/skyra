// Goal — the PFC. Composed of sub-binding realities.
// Tracks progress via comparator: setpoint vs actual state.
// Proposer: collapses to primitive that closes the gap.
// Signals Episodic on completion/failure (episode boundary).
//
// Sub-binding realities:
//   Coherence — contradiction monitor. Absorb or split. Can raise external goal.
//   Certainty — prediction engine. Compare, predict, signal. Can raise external goal.
//   Prospective — external obligations. Tracks delta toward resolution.
//
// Four outcome categories on ascent:
//   1. Match — flat reinforcement, episode complete.
//   2. Better than expected — heavy reinforcement.
//   3. Controllable mismatch — moderate reinforcement, persist.
//   4. Uncontrollable mismatch — decay, abandon, signal Motivation.
