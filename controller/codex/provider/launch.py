#!/usr/bin/env python3
"""Prepare and launch a Codex process under mandatory external Seatbelt."""
import argparse
import json
import os
from pathlib import Path
import select
import socket
import subprocess
import sys
import tempfile
import time
from sandbox import native_binary, render

# Disabled Codex features. view_image and live web search stay on so Codex
# can look at photos and read the internet until Skyra has its own tools
# (proposal 38). Native reads are not recorded in the lineage. Image access
# stays under the Horizon's read grants; web search runs at the provider.
FEATURES = ['apps', 'plugins', 'hooks', 'daemon_auto_start', 'browser_use',
            'browser_use_external', 'computer_use', 'image_generation',
            'multi_agent', 'multi_agent_v2', 'shell_snapshot', 'code_mode', 'code_mode_only',
            'code_mode_host', 'goals', 'sleep_tool', 'current_time_reminder',
            'shell_tool', 'skill_search', 'request_permissions_tool',
            'send_message_to_user_async', 'token_budget']
# Every prompt Codex adds of its own is off (proposal 38): Skyra's header is the
# whole prompt. Keep in step with codex/launch/launch.go's quiet.
QUIET = ('include_permissions_instructions = false\ninclude_apps_instructions = false\n'
         'include_collaboration_mode_instructions = false\ninclude_environment_context = false\n'
         'project_doc_max_bytes = 0\n')
EGRESS_HOSTS = ('chatgpt.com', 'api.openai.com', 'auth.openai.com')
# The one Codex version the isolation is verified for. Changing it means
# rerunning controller/experiments/appserver/tool_surface.py and the probes;
# codex/launch/launch.go pins the same version.
CODEX_VERSION = '0.160.0'


def verified_version(binary):
    version = subprocess.check_output([str(binary), '--version'], text=True).strip().split()[-1]
    if version != CODEX_VERSION:
        raise RuntimeError(f'direct tool isolation is verified for Codex {CODEX_VERSION}, not {version}; validate the tool-surface test before changing the pin')
    return version


def direct_catalog(binary, cache_file=None):
    # Read metadata generated by this exact binary in its isolated home.
    cache_file = cache_file or (Path.home() / '.codex/models_cache.json')
    cache = json.loads(cache_file.read_text())
    version = verified_version(binary)
    if cache.get('client_version') != version or not cache.get('models'):
        raise RuntimeError('isolated Codex model metadata does not match the installed version')
    for model in cache['models']:
        model['tool_mode'] = 'standard'
        model['multi_agent_version'] = 'disabled'
        model['experimental_supported_tools'] = []
        model['apply_patch_tool_type'] = None  # no native file edits (see codex/launch/launch.go)
        model['supports_search_tool'] = False  # deferred tool discovery stays off
        model['use_responses_lite'] = False  # the lite API omits hosted web search
        model['include_skills_usage_instructions'] = False
        model['include_plugin_usage_instructions'] = False
        model['include_apps_usage_instructions'] = False
    return {'models': cache['models']}


def configuration(run, capture_port=None):
    if capture_port is not None:
        # Test only: inference goes to a local capture server, never a model.
        return ('model_provider = "capture"\n' + configuration(run) +
                f'[model_providers.capture]\nname = "capture"\nbase_url = "http://127.0.0.1:{capture_port}/v1"\n'
                'wire_api = "responses"\nrequires_openai_auth = false\n[features]\nenable_request_compression = false\n')
    return 'model_catalog_json = ' + json.dumps(str(run / 'models.json')) + '\n' + 'cli_auth_credentials_store = "file"\nweb_search = "live"\nsandbox_mode = "read-only"\napproval_policy = "never"\n' + QUIET + '[agents]\nenabled = false\n[tools.experimental_request_user_input]\nenabled = false\n[tools.update_plan]\nenabled = false\n[skills.bundled]\nenabled = false\n'


def prepare(state, binary=None):
    if sys.platform != 'darwin':
        raise RuntimeError('the provider requires macOS Seatbelt')
    binary = (binary or native_binary()).resolve(strict=True)
    verified_version(binary)
    for executable in [binary, Path('/usr/bin/sandbox-exec')]:
        if not executable.is_file() or not os.access(executable, os.X_OK):
            raise RuntimeError(f'missing executable: {executable}')
    auth = (Path.home() / '.codex/auth.json').resolve(strict=True)
    state.mkdir(parents=True, exist_ok=True, mode=0o700)
    run = Path(tempfile.mkdtemp(prefix='provider-', dir=state)).resolve()
    home, scratch, work = [run / name for name in ['home', 'tmp', 'work']]
    for directory in [home, scratch, work]:
        directory.mkdir(mode=0o700)
    (home / 'auth.json').symlink_to(auth)
    # Bootstrap performs no inference. It initializes under the same external
    # sandbox and proxy, creating a version-matched catalog in this home.
    (home / 'config.toml').write_text('cli_auth_credentials_store = "file"\nweb_search = "disabled"\nsandbox_mode = "read-only"\napproval_policy = "never"\n')
    (run / 'launch.json').write_text(json.dumps({'binary': str(binary)}))
    return run


def environment(run, proxy_port):
    return {'PATH': '/usr/bin:/bin', 'HOME': str(run / 'home'),
            'CODEX_HOME': str(run / 'home'), 'TMPDIR': str(run / 'tmp'),
            'HTTPS_PROXY': f'http://127.0.0.1:{proxy_port}'}


def actor_argv(run, binary):
    argv = ['/usr/bin/sandbox-exec', '-f', str(run / 'actor.sb'), str(binary)]
    for feature in FEATURES:
        argv.extend(['--disable', feature])
    argv.extend(['--enable', 'skip_host_skill_discovery', '--enable', 'view_image', 'app-server', '--listen', 'stdio://'])
    return argv


def bootstrap_catalog(run, binary, env, capture_port=None):
    with (run / 'bootstrap.stderr').open('ab') as log:
        actor = subprocess.Popen(actor_argv(run, binary), env=env, cwd=run / 'work',
                                 stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=log)
        try:
            request = {'id': 'initialize', 'method': 'initialize', 'params': {
                'clientInfo': {'name': 'skyra-bootstrap', 'version': '1'},
                'capabilities': {'experimentalApi': True}}}
            actor.stdin.write(json.dumps(request).encode() + b'\n')
            actor.stdin.flush()
            ready, _, _ = select.select([actor.stdout], [], [], 20)
            if not ready:
                raise RuntimeError('isolated Codex bootstrap did not initialize; see bootstrap.stderr')
            answer = json.loads(actor.stdout.readline())
            if 'result' not in answer or answer.get('id') != 'initialize':
                raise RuntimeError('isolated Codex bootstrap refused initialization')
            cache_file = run / 'home' / 'models_cache.json'
            deadline = time.monotonic() + 10
            while not cache_file.exists() and time.monotonic() < deadline:
                time.sleep(.05)
            if not cache_file.exists():
                raise RuntimeError('isolated Codex bootstrap did not write model metadata')
            (run / 'models.json').write_text(json.dumps(direct_catalog(binary, cache_file)))
            (run / 'home' / 'config.toml').write_text(configuration(run, capture_port))
        finally:
            actor.terminate()
            try:
                actor.wait(timeout=5)
            except subprocess.TimeoutExpired:
                actor.kill()
                actor.wait()


def launch(run, capture_port=None):
    manifest = json.loads((run / 'launch.json').read_text())
    binary = Path(manifest['binary'])
    auth = (Path.home() / '.codex/auth.json').resolve(strict=True)
    ready_file = run / 'proxy.port'
    journal = run / 'proxy.jsonl'
    proxy_log = (run / 'proxy.stderr').open('ab')
    proxy_args = [sys.executable, str(Path(__file__).with_name('proxy.py')),
                  '--journal', str(journal), '--ready', str(ready_file)]
    for host in EGRESS_HOSTS:
        proxy_args.extend(['--allow', host])
    proxy = subprocess.Popen(proxy_args, stdout=proxy_log, stderr=proxy_log)
    actor = None
    try:
        deadline = time.monotonic() + 10
        while not ready_file.exists():
            if proxy.poll() is not None:
                raise RuntimeError('egress proxy exited before binding; see proxy.stderr')
            if time.monotonic() >= deadline:
                raise RuntimeError('egress proxy did not bind; see proxy.stderr')
            time.sleep(.05)
        port = int(ready_file.read_text())
        if proxy.poll() is not None:
            raise RuntimeError('egress proxy exited after binding')
        (run / 'actor.sb').write_text(render(binary, run / 'home', run / 'tmp', run / 'work', auth, port, capture_port))
        env = environment(run, port)
        # Validate the actual restrictive profile before the host sees an actor.
        subprocess.run(['/usr/bin/sandbox-exec', '-f', str(run / 'actor.sb'), str(binary), '--version'],
                       env=env, cwd=run / 'work', stdout=subprocess.DEVNULL, check=True)
        # The catalog comes from the provider through the proxy, as in
        # production, even when a capture server takes inference afterwards.
        bootstrap_catalog(run, binary, env, capture_port)
        actor = subprocess.Popen(actor_argv(run, binary), env=env, cwd=run / 'work',
                                 stdin=sys.stdin, stdout=sys.stdout, stderr=sys.stderr)
        # The actor alone owns the protocol pipes. The launcher only supervises
        # the proxy and exits when the actor does.
        sys.stdin.close()
        sys.stdout.close()
        while actor.poll() is None:
            if proxy.poll() is not None:
                actor.terminate()
                raise RuntimeError('egress proxy exited while the actor was running')
            time.sleep(.25)
        return actor.returncode
    finally:
        if actor is not None and actor.poll() is None:
            actor.terminate()
            try:
                actor.wait(timeout=5)
            except subprocess.TimeoutExpired:
                actor.kill()
                actor.wait()
        proxy.terminate()
        try:
            proxy.wait(timeout=5)
        except subprocess.TimeoutExpired:
            proxy.kill()
            proxy.wait()
        proxy_log.close()


def ready(path):
    deadline = time.monotonic() + 20
    while not path.exists():
        if time.monotonic() >= deadline:
            raise RuntimeError('host socket did not appear')
        time.sleep(.05)
    with socket.socket(socket.AF_UNIX) as sock:
        sock.settimeout(20)
        sock.connect(str(path))
        stream = sock.makefile('rwb')
        def call(value):
            # Host deduplicates bytes; match Go encoding/json's sorted maps.
            stream.write(json.dumps(value, sort_keys=True, separators=(',', ':')).encode() + b'\n'); stream.flush()
            answer = json.loads(stream.readline())
            if 'error' in answer:
                raise RuntimeError(answer['error'])
            return answer
        # Same stable initialization ID and payload as the adapter: replayed
        # delivery is a no-op. Readiness means the provider actually answered.
        result = call({'op': 'deliver', 'id': 'initialize', 'line': {
            'id': 'initialize', 'method': 'initialize', 'params': {
                'clientInfo': {'name': 'skyra', 'version': '1'},
                'capabilities': {'experimentalApi': True}}}})
        position = result['seq']
        while time.monotonic() < deadline:
            batch = call({'op': 'read', 'from': position, 'wait_ms': 1000})
            position = batch['next']
            for event in batch.get('events') or []:
                if event.get('host'):
                    raise RuntimeError(event['host'])
                message = event.get('line', {})
                if message.get('id') == 'initialize' and 'result' in message:
                    if not call({'op': 'ping'}).get('alive'):
                        raise RuntimeError('provider exited after initialization')
                    return
                if message.get('id') == 'initialize' and 'error' in message:
                    raise RuntimeError('provider initialization failed')
        raise RuntimeError('provider initialization timed out')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    action = parser.add_mutually_exclusive_group(required=True)
    action.add_argument('--prepare', type=Path)
    action.add_argument('--launch', type=Path)
    action.add_argument('--ready', type=Path)
    action.add_argument('--check', action='store_true')
    parser.add_argument('--codex', type=Path)
    parser.add_argument('--capture-port', type=int, help='test only: send inference to a local capture server')
    args = parser.parse_args()
    if args.check:
        if sys.platform != 'darwin' or not Path('/usr/bin/sandbox-exec').is_file():
            raise RuntimeError('macOS Seatbelt is required')
        if not (Path.home() / '.codex/auth.json').is_file():
            raise RuntimeError('run codex login with file-based credentials first')
        verified_version((args.codex or native_binary()).resolve(strict=True))
        print(f'Codex {CODEX_VERSION} login ready; model metadata is generated in each isolated provider home')
    elif args.prepare:
        print(prepare(args.prepare, args.codex))
    elif args.launch:
        sys.exit(launch(args.launch.resolve(strict=True), args.capture_port))
    else:
        ready(args.ready)


if __name__ == '__main__':
    try:
        main()
    except Exception as error:
        print(f'codex provider: {error}', file=sys.stderr)
        sys.exit(1)
